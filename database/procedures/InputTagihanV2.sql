USE bekasi_sdit_gema_nurani;

DROP PROCEDURE IF EXISTS InputTagihanV2;

DELIMITER $$

CREATE PROCEDURE InputTagihanV2(
    IN p_NOCUST     VARCHAR(32),
    IN p_NOMINAL    BIGINT,
    IN p_NMTagihan  VARCHAR(70),
    IN p_BILLPERIOD VARCHAR(50),
    IN p_BTA        VARCHAR(50),
    IN p_isNYICIL   VARCHAR(5),
    IN p_BILLCD     VARCHAR(50),
    IN p_TGL_AKTIF  VARCHAR(30),
    IN p_TGL_EXPIRED VARCHAR(30)
)
main: BEGIN
    DECLARE v_CUSTID BIGINT DEFAULT NULL;
    DECLARE v_BILLCD VARCHAR(50);
    DECLARE v_BILLACC VARCHAR(20);
    DECLARE v_URUT INT DEFAULT 1;
    DECLARE v_CICIL INT DEFAULT 0;
    DECLARE v_AA BIGINT DEFAULT 1;
    DECLARE v_TGL DATETIME;
    DECLARE v_EXP DATETIME;

    DECLARE EXIT HANDLER FOR SQLEXCEPTION
    BEGIN
        ROLLBACK;
        RESIGNAL;
    END;

    START TRANSACTION;

    SELECT CUSTID INTO v_CUSTID
    FROM scctcust
    WHERE NOCUST = p_NOCUST OR NOVA = p_NOCUST
    LIMIT 1;

    IF v_CUSTID IS NULL THEN
        ROLLBACK;
        SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'Siswa tidak ditemukan untuk tagihan';
    END IF;

    SET v_BILLCD = TRIM(IFNULL(p_BILLCD, ''));
    SET v_URUT = IF(p_BILLPERIOD REGEXP '^[0-9]+$', CAST(p_BILLPERIOD AS UNSIGNED), 1);
    IF v_BILLCD = '' THEN
        SET v_BILLCD = CONCAT(DATE_FORMAT(NOW(), '%Y/i%m-'), LPAD(v_URUT + 1, 3, '0'));
    END IF;

    IF p_TGL_AKTIF IS NOT NULL AND TRIM(p_TGL_AKTIF) <> '' THEN
        SET v_TGL = STR_TO_DATE(LEFT(p_TGL_AKTIF, 10), '%Y-%m-%d');
    END IF;
    IF v_TGL IS NULL THEN
        SET v_TGL = NOW();
    END IF;

    IF p_TGL_EXPIRED IS NOT NULL AND TRIM(p_TGL_EXPIRED) <> '' THEN
        SET v_EXP = STR_TO_DATE(LEFT(p_TGL_EXPIRED, 10), '%Y-%m-%d');
    END IF;

    SET v_BILLACC = DATE_FORMAT(v_TGL, '%Y%m');
    SET v_CICIL = IF(UPPER(TRIM(IFNULL(p_isNYICIL, '0'))) IN ('1', 'Y', 'YA'), 1, 0);

    SELECT IFNULL(MAX(AA), 0) + 1 INTO v_AA FROM scctbill;

    INSERT INTO scctbill (
        AA, CUSTID, BILLCODE, BILLACC, BILLNM,
        BILLAMT, BILLPAID, PAYMENTLEFT, FLPART,
        INSTALLMENT, isINSTALLABLE, PAIDST
    ) VALUES (
        v_AA, v_CUSTID, v_BILLCD, v_BILLACC, p_NMTagihan,
        p_NOMINAL, 0, p_NOMINAL, 0,
        0, v_CICIL, 0
    );

    COMMIT;
END$$

DELIMITER ;
